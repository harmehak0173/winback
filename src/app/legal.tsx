import { useLocalSearchParams, useRouter } from 'expo-router';
import React from 'react';
import { Alert, Linking, Pressable, ScrollView, StyleSheet, Text, View } from 'react-native';
import { Screen } from '@/components/Screen';
import { LAST_UPDATED, LEGAL_DOCS, type LegalDoc } from '@/state/legal';
import { colors, fonts, spacing, tracking } from '@/theme/tokens';

/**
 * In-app Terms / Privacy and the other legal pages. Bundled rather than
 * linked out so the store-required disclosures are always reachable, with or
 * without a hosted URL and with or without a network connection.
 *
 * `?doc=` is a LEGAL_DOCS key (privacy, terms, health-data, delete-account,
 * support); anything else shows the Privacy Policy. Links inside the text
 * open the other bundled pages in place, and mail/web links hand off to the
 * system.
 */

// Hosted copies (site/, generated by scripts/sync-legal.mjs). Read statically
// so Expo inlines them at build time. The health-data page has its own
// variable; without it, it is assumed to sit next to privacy.html - but only
// when the privacy URL really names that file. A pretty URL such as
// https://host/privacy/ would otherwise become .../privacy/health-data.html,
// a page that does not exist, so no hosted link is offered then.
const PRIVACY_URL = httpsOnly(process.env.EXPO_PUBLIC_PRIVACY_URL);
const HEALTH_DATA_URL =
  httpsOnly(process.env.EXPO_PUBLIC_HEALTH_DATA_URL) ??
  (PRIVACY_URL && /\/[^/]+\.html$/.test(PRIVACY_URL)
    ? PRIVACY_URL.replace(/[^/]*$/, 'health-data.html')
    : null);
const HOSTED: Record<LegalDoc, string | null> = {
  privacy: PRIVACY_URL,
  terms: httpsOnly(process.env.EXPO_PUBLIC_TERMS_URL),
  'delete-account': httpsOnly(process.env.EXPO_PUBLIC_DELETE_URL),
  support: httpsOnly(process.env.EXPO_PUBLIC_SUPPORT_URL),
  'health-data': HEALTH_DATA_URL,
};

function httpsOnly(url: string | undefined): string | null {
  const trimmed = url?.trim();
  return trimmed && trimmed.startsWith('https://') ? trimmed : null;
}

function isLegalDoc(value: string | undefined): value is LegalDoc {
  return value != null && Object.prototype.hasOwnProperty.call(LEGAL_DOCS, value);
}

type Span = { text: string; target?: string };

/** Split a line into plain text and [label](target) links. */
function parseInline(line: string): Span[] {
  const spans: Span[] = [];
  const link = /\[([^\]]+)\]\(([^)\s]+)\)/g;
  let last = 0;
  for (const m of line.matchAll(link)) {
    const at = m.index ?? 0;
    if (at > last) spans.push({ text: line.slice(last, at) });
    spans.push({ text: m[1], target: m[2] });
    last = at + m[0].length;
  }
  if (last < line.length) spans.push({ text: line.slice(last) });
  return spans;
}

export default function Legal() {
  const router = useRouter();
  const { doc } = useLocalSearchParams<{ doc?: string }>();
  const key: LegalDoc = isLegalDoc(doc) ? doc : 'privacy';
  const { title, body } = LEGAL_DOCS[key];
  const hosted = HOSTED[key];

  const close = () => (router.canGoBack() ? router.back() : router.replace('/'));

  const open = (target: string) => {
    if (target.startsWith('doc:')) {
      const next = target.slice(4);
      if (isLegalDoc(next)) router.push({ pathname: '/legal', params: { doc: next } });
      return;
    }
    // No mail app, or no browser: show the address so it can be used from
    // somewhere else. These links are the route to privacy rights and to
    // deletion, so a tap that does nothing is not good enough.
    Linking.openURL(target).catch(() => {
      const address = target.replace(/^mailto:/, '');
      Alert.alert(target.startsWith('mailto:') ? 'Email us' : 'Open this address', address);
    });
  };

  const renderInline = (line: string) =>
    parseInline(line).map((span, i) =>
      span.target ? (
        <Text
          key={i}
          style={styles.link}
          onPress={() => open(span.target!)}
          accessibilityRole="link"
        >
          {span.text}
        </Text>
      ) : (
        span.text
      ),
    );

  return (
    <Screen edges={['top']}>
      <View style={styles.bar}>
        <Pressable onPress={close} hitSlop={12} accessibilityRole="button">
          <Text style={styles.close}>Close</Text>
        </Pressable>
      </View>
      <ScrollView contentContainerStyle={styles.content}>
        <Text style={styles.title} accessibilityRole="header">
          {title}
        </Text>
        <Text style={styles.updated}>Last updated: {LAST_UPDATED}</Text>
        {body.split('\n').map((line, i) => {
          const trimmed = line.trim();
          if (!trimmed) return <View key={i} style={styles.gap} />;
          if (trimmed.startsWith('### ')) {
            return (
              <Text key={i} style={styles.subheading} accessibilityRole="header">
                {renderInline(trimmed.slice(4))}
              </Text>
            );
          }
          if (trimmed.startsWith('## ')) {
            return (
              <Text key={i} style={styles.heading} accessibilityRole="header">
                {renderInline(trimmed.slice(3))}
              </Text>
            );
          }
          if (trimmed.startsWith('- ')) {
            return (
              <View key={i} style={styles.bulletRow}>
                <Text style={styles.bulletDot}>-</Text>
                <Text style={styles.bullet}>{renderInline(trimmed.slice(2))}</Text>
              </View>
            );
          }
          return (
            <Text key={i} style={styles.para}>
              {renderInline(trimmed)}
            </Text>
          );
        })}
        {hosted && (
          <View style={styles.hosted}>
            <Text style={styles.hostedLabel}>Also online</Text>
            <Text style={styles.link} onPress={() => open(hosted)} accessibilityRole="link">
              {hosted}
            </Text>
          </View>
        )}
      </ScrollView>
    </Screen>
  );
}

const styles = StyleSheet.create({
  bar: { paddingHorizontal: spacing.screenX, paddingTop: 8, paddingBottom: 4, alignItems: 'flex-end' },
  close: { fontFamily: fonts.display.bold, fontSize: 15, color: colors.accent },
  content: { paddingHorizontal: spacing.screenX, paddingBottom: 48 },
  title: {
    fontFamily: fonts.display.extrabold,
    fontSize: 26,
    letterSpacing: tracking(26),
    color: colors.text,
  },
  updated: { fontFamily: fonts.body.regular, fontSize: 12, color: colors.textFaint, marginTop: 4, marginBottom: 12 },
  heading: {
    fontFamily: fonts.display.bold,
    fontSize: 16,
    color: colors.text,
    marginTop: 20,
    marginBottom: 6,
  },
  subheading: {
    fontFamily: fonts.display.semibold,
    fontSize: 14,
    color: colors.text,
    marginTop: 14,
    marginBottom: 4,
  },
  para: {
    fontFamily: fonts.body.regular,
    fontSize: 14,
    lineHeight: 14 * 1.6,
    color: colors.textMuted,
    marginTop: 6,
  },
  link: {
    fontFamily: fonts.body.medium,
    color: colors.accent,
    textDecorationLine: 'underline',
  },
  bulletRow: { flexDirection: 'row', gap: 8, marginTop: 6, paddingRight: 4 },
  bulletDot: { fontFamily: fonts.body.regular, fontSize: 14, lineHeight: 14 * 1.6, color: colors.textDim },
  bullet: {
    flex: 1,
    fontFamily: fonts.body.regular,
    fontSize: 14,
    lineHeight: 14 * 1.6,
    color: colors.textMuted,
  },
  gap: { height: 2 },
  hosted: {
    marginTop: 28,
    paddingTop: 14,
    borderTopWidth: StyleSheet.hairlineWidth,
    borderTopColor: colors.hairline,
    gap: 4,
  },
  hostedLabel: { fontFamily: fonts.body.regular, fontSize: 12, color: colors.textFaint },
});
